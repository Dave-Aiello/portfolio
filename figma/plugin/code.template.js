/* Steady screens: builds the prototype as editable Figma frames.
   Generated by figma/build.js from the live prototype. Run once in an empty
   Figma file: Plugins > Development > Import plugin from manifest. */

const DATA = /*__DATA__*/null;

const W = 390, H = 844, GAP = 120;

const TOKENS = [
  ["Background", "#f6f5f2"], ["Surface/Default", "#ffffff"], ["Surface/Muted", "#efede8"], ["Border", "#e2dfd8"],
  ["Text/Primary", "#17150f"], ["Text/Secondary", "#5b574e"], ["Text/Tertiary", "#8a857a"],
  ["Brand/Primary", "#14532d"], ["Brand/Soft", "#e3efe6"], ["Status/Positive", "#15803d"], ["Status/Negative", "#b42318"],
  ["Notice/Warning bg", "#fdf3dc"], ["Notice/Warning text", "#6b4a05"], ["Notice/Danger bg", "#fde8e6"], ["Notice/Danger text", "#7a1a12"],
  ["Asset/Bitcoin", "#e8890c"], ["Asset/Ethereum", "#5b5f97"], ["Asset/USDC", "#2a6fb0"], ["Device/Black", "#0c0c0b"]
];

/* size/weight -> text style name */
const TYPE = {
  "64/700": "Display/Amount", "44/700": "Display/Balance", "30/700": "Heading/Title", "20/600": "Heading/Section",
  "17/600": "Body/Headline", "16/400": "Body/Large", "16/500": "Body/Emphasis", "16/600": "Body/Strong",
  "15/400": "Body/Default", "15/500": "Body/Default emphasis", "15/600": "Body/Section label", "14/400": "Body/Small",
  "13/400": "Caption/Default", "13/600": "Caption/Strong", "12/400": "Caption/Small", "11/400": "Caption/Tab"
};

const WEIGHT = { 400: "Regular", 500: "Medium", 600: "Semi Bold", 700: "Bold" };

const ctx = {
  vars: {}, textStyles: {}, mono: null, comps: {}, sets: {}, frames: {}, clicks: []
};

function hex(c) {
  const h = (v) => Math.round(v * 255).toString(16).padStart(2, "0");
  return "#" + h(c.r) + h(c.g) + h(c.b);
}
function rgb(hexStr) {
  const n = parseInt(hexStr.slice(1), 16);
  return { r: ((n >> 16) & 255) / 255, g: ((n >> 8) & 255) / 255, b: (n & 255) / 255 };
}
function paint(c) {
  let p = { type: "SOLID", color: { r: c.r, g: c.g, b: c.b }, opacity: c.a };
  const v = ctx.vars[hex(c)];
  if (v && c.a === 1) p = figma.variables.setBoundVariableForPaint(p, "color", v);
  return p;
}

async function setupTokens() {
  const coll = figma.variables.createVariableCollection("Steady tokens");
  const mode = coll.modes[0].modeId;
  coll.renameMode(mode, "Light");
  for (const [name, h] of TOKENS) {
    const v = figma.variables.createVariable(name, coll, "COLOR");
    v.setValueForMode(mode, Object.assign(rgb(h), { a: 1 }));
    ctx.vars[h] = v;
  }
}

async function setupFonts() {
  for (const w of Object.values(WEIGHT)) await figma.loadFontAsync({ family: "Inter", style: w });
  const all = await figma.listAvailableFontsAsync();
  const has = (fam, style) => all.some((f) => f.fontName.family === fam && f.fontName.style === style);
  for (const fam of ["Geist Mono", "JetBrains Mono", "Roboto Mono", "Source Code Pro"]) {
    if (has(fam, "Regular") && has(fam, "Medium")) { ctx.mono = fam; break; }
  }
  if (ctx.mono) {
    await figma.loadFontAsync({ family: ctx.mono, style: "Regular" });
    await figma.loadFontAsync({ family: ctx.mono, style: "Medium" });
  }
}

function fontFor(st) {
  if (st.family === "mono" && ctx.mono) return { family: ctx.mono, style: st.weight >= 500 ? "Medium" : "Regular" };
  return { family: "Inter", style: WEIGHT[st.weight] || "Regular" };
}

function textStyleFor(st) {
  if (st.family === "mono") return null;
  const key = Math.round(st.size) + "/" + st.weight;
  const name = TYPE[key];
  if (!name) return null;
  const id = name + "|" + (st.lineHeight || "auto") + "|" + st.letterSpacing;
  if (ctx.textStyles[id]) return ctx.textStyles[id];
  const s = figma.createTextStyle();
  const dupes = Object.keys(ctx.textStyles).filter((k) => k.split("|")[0] === name).length;
  s.name = dupes ? name + " " + (dupes + 1) : name;
  s.fontName = fontFor(st);
  s.fontSize = st.size;
  s.lineHeight = st.lineHeight ? { unit: "PIXELS", value: st.lineHeight } : { unit: "AUTO" };
  s.letterSpacing = { unit: "PIXELS", value: st.letterSpacing };
  ctx.textStyles[id] = s;
  return s;
}

async function makeText(n, parent) {
  const t = figma.createText();
  parent.appendChild(t);
  t.fontName = fontFor(n.style);
  t.characters = n.chars;
  t.fontSize = n.style.size;
  t.lineHeight = n.style.lineHeight ? { unit: "PIXELS", value: n.style.lineHeight } : { unit: "AUTO" };
  t.letterSpacing = { unit: "PIXELS", value: n.style.letterSpacing };
  if (n.style.decoration) t.textDecoration = n.style.decoration;
  const ts = textStyleFor(n.style);
  if (ts) await t.setTextStyleIdAsync(ts.id);
  if (n.style.color) t.fills = [paint(n.style.color)];
  if (n.wrap) {
    t.resize(Math.max(1, n.w + 1), Math.max(1, n.h));
    t.textAutoResize = "HEIGHT";
    t.textAlignHorizontal = n.style.align === "center" ? "CENTER" : n.style.align === "right" || n.style.align === "end" ? "RIGHT" : "LEFT";
  } else {
    t.textAutoResize = "WIDTH_AND_HEIGHT";
  }
  t.name = n.chars.slice(0, 40);
  t.x = n.x;
  t.y = n.y;
  return t;
}

function makeSvg(n, parent) {
  const s = figma.createNodeFromSvg(n.svg);
  s.name = n.name;
  parent.appendChild(s);
  s.x = n.x;
  s.y = n.y;
  return s;
}

function styleFrame(f, n) {
  f.name = n.name;
  f.resize(Math.max(0.01, n.w), Math.max(0.01, n.h));
  f.fills = n.fill ? [paint(n.fill)] : [];
  if (n.stroke && n.stroke.color) {
    f.strokes = [paint(n.stroke.color)];
    f.strokeAlign = "INSIDE";
    const s = n.stroke;
    if (s.top === s.right && s.top === s.bottom && s.top === s.left) f.strokeWeight = s.top;
    else {
      f.strokeTopWeight = s.top; f.strokeRightWeight = s.right;
      f.strokeBottomWeight = s.bottom; f.strokeLeftWeight = s.left;
    }
  }
  const r = n.radius;
  f.topLeftRadius = r[0]; f.topRightRadius = r[1]; f.bottomRightRadius = r[2]; f.bottomLeftRadius = r[3];
  f.clipsContent = !!n.clip;
  if (n.opacity < 1) f.opacity = n.opacity;
  if (n.shadow && n.shadow.color) {
    f.effects = [{ type: "DROP_SHADOW", color: { r: n.shadow.color.r, g: n.shadow.color.g, b: n.shadow.color.b, a: n.shadow.color.a },
      offset: { x: n.shadow.x, y: n.shadow.y }, radius: n.shadow.blur, spread: 0, visible: true, blendMode: "NORMAL" }];
  }
}

async function buildChildren(n, f, frameId) {
  for (const c of n.children || []) await buildNode(c, f, frameId);
}

function autoLayout(comp, n, hug) {
  const t = (n.children || []).find((c) => c.type === "text");
  comp.layoutMode = "HORIZONTAL";
  comp.primaryAxisAlignItems = "CENTER";
  comp.counterAxisAlignItems = "CENTER";
  if (hug && t) {
    comp.paddingLeft = comp.paddingRight = Math.round(t.x);
    comp.paddingTop = comp.paddingBottom = Math.max(0, Math.round((n.h - t.h) / 2));
    comp.primaryAxisSizingMode = "AUTO";
    comp.counterAxisSizingMode = "AUTO";
  } else {
    comp.primaryAxisSizingMode = "FIXED";
    comp.counterAxisSizingMode = "FIXED";
  }
}

async function buildNode(n, parent, frameId) {
  if (n.type === "text") return makeText(n, parent);
  if (n.type === "svg") return makeSvg(n, parent);

  let node;
  if (n.comp) {
    const key = n.comp.set + "|" + (n.comp.variant || "");
    let comp = ctx.comps[key];
    if (!comp) {
      comp = figma.createComponent();
      ctx.holder.appendChild(comp);
      styleFrame(comp, n);
      comp.name = n.comp.variant || n.comp.set;
      await buildChildren(n, comp, frameId);
      if (n.comp.set === "Button" || n.comp.set === "Keypad key") autoLayout(comp, n, false);
      if (n.comp.set === "Chip") autoLayout(comp, n, true);
      ctx.comps[key] = comp;
      (ctx.sets[n.comp.set] = ctx.sets[n.comp.set] || []).push(comp);
      comp.setPluginData("w", String(n.w));
    }
    node = comp.createInstance();
    parent.appendChild(node);
    if (Math.abs(node.width - n.w) > 0.5 || Math.abs(node.height - n.h) > 0.5) {
      if (n.comp.set !== "Chip") node.resize(n.w, n.h);
    }
    const t = (n.children || []).find((c) => c.type === "text");
    const it = node.findOne((c) => c.type === "TEXT");
    if (t && it && it.characters !== t.chars) it.characters = t.chars;
    if (n.fill && hex(n.fill) !== hex(comp.fills[0] && comp.fills[0].color ? comp.fills[0].color : { r: 2, g: 2, b: 2 })) node.fills = [paint(n.fill)];
    node.x = n.x;
    node.y = n.y;
  } else {
    node = figma.createFrame();
    parent.appendChild(node);
    styleFrame(node, n);
    node.x = n.x;
    node.y = n.y;
    await buildChildren(n, node, frameId);
  }
  if (n.click !== undefined) ctx.clicks.push({ node, frameId, click: n.click });
  return node;
}

function label(text, size, weight, x, y, width, color) {
  const t = figma.createText();
  t.fontName = { family: "Inter", style: WEIGHT[weight] };
  t.characters = text;
  t.fontSize = size;
  t.lineHeight = { unit: "PERCENT", value: 145 };
  t.fills = [{ type: "SOLID", color: rgb(color || "#17150f") }];
  if (width) { t.resize(width, 20); t.textAutoResize = "HEIGHT"; }
  t.x = x; t.y = y;
  return t;
}

async function run() {
  if (!DATA) throw new Error("No screen data. Run figma/build.js first.");
  figma.currentPage.name = "Steady: first crypto buy";
  await setupFonts();
  await setupTokens();

  /* holder for components until they are combined into sets */
  ctx.holder = figma.createFrame();
  ctx.holder.name = "Components (building)";
  ctx.holder.fills = [];
  ctx.holder.clipsContent = false;

  const groups = [
    { name: "1. First buy", ids: ["home", "intro", "choose", "amount", "amount-filled", "amount-over", "review", "review-faceid", "review-expired", "success"] },
    { name: "2. Moving it to your own wallet", ids: ["holding", "send-address", "send-pasted", "send-check", "send-test", "sent"] }
  ];
  const byId = {};
  DATA.frames.forEach((f) => { byId[f.id] = f; });

  const header = label("Steady: a first crypto purchase inside an everyday money app", 40, 700, 0, -360);
  const sub = label("Concept, 2026. Every frame is clickable: select the Home frame and press Present. Prices, balances and addresses are examples.", 20, 400, 0, -296, 1400, "#5b574e");
  figma.currentPage.appendChild(header);
  figma.currentPage.appendChild(sub);

  let y = 0;
  const sections = [];
  for (const g of groups) {
    const section = figma.createSection();
    section.name = g.name;
    const pad = 80;
    let x = pad;
    for (const id of g.ids) {
      const f = byId[id];
      if (!f) continue;
      const frame = figma.createFrame();
      section.appendChild(frame);
      styleFrame(frame, Object.assign({}, f.tree, { name: f.title }));
      frame.x = x;
      frame.y = pad + 40;
      frame.clipsContent = true;
      await buildChildren(f.tree, frame, id);
      ctx.frames[id] = frame;
      const t1 = label(f.title, 20, 600, x, pad + 40 + H + 32);
      const t2 = label(f.note, 15, 400, x, pad + 40 + H + 68, W, "#5b574e");
      section.appendChild(t1);
      section.appendChild(t2);
      x += W + GAP;
    }
    section.resizeWithoutConstraints(x - GAP + pad, H + 480);
    section.x = 0;
    section.y = y;
    y += H + 480 + 160;
    sections.push(section);
  }

  /* component sets */
  const compSection = figma.createSection();
  compSection.name = "Components";
  let cx = 80;
  for (const [setName, comps] of Object.entries(ctx.sets)) {
    let node;
    if (comps.length > 1 || comps[0].name.indexOf("=") > -1) {
      node = figma.combineAsVariants(comps, compSection);
      node.name = setName;
      node.layoutMode = "HORIZONTAL";
      node.layoutWrap = "WRAP";
      node.counterAxisSizingMode = "AUTO";
      node.primaryAxisSizingMode = "FIXED";
      node.resize(Math.min(1200, comps.reduce((s, c) => s + c.width + 24, 48)), node.height);
      node.itemSpacing = 24;
      node.counterAxisSpacing = 24;
      node.paddingLeft = node.paddingRight = node.paddingTop = node.paddingBottom = 24;
      node.strokes = [{ type: "SOLID", color: rgb("#9747ff") }];
      node.dashPattern = [6, 4];
      node.cornerRadius = 8;
    } else {
      node = comps[0];
      compSection.appendChild(node);
    }
    node.x = cx;
    node.y = 120;
    cx += node.width + 80;
  }
  compSection.appendChild(label("Components", 24, 700, 80, 48));
  compSection.resizeWithoutConstraints(Math.max(cx, 1200), 120 + Math.max(...Object.values(ctx.sets).map(() => 0), 0) + 600);
  compSection.x = 0;
  compSection.y = y;
  ctx.holder.remove();

  /* prototype links */
  let links = 0;
  for (const c of ctx.clicks) {
    const f = byId[c.frameId];
    const target = f.links[c.click];
    const dest = target && ctx.frames[target];
    if (!dest) continue;
    await c.node.setReactionsAsync([{
      trigger: { type: "ON_CLICK" },
      actions: [{ type: "NODE", destinationId: dest.id, navigation: "NAVIGATE",
        transition: { type: "DISSOLVE", easing: { type: "EASE_OUT" }, duration: 0.2 }, preserveScrollPosition: false }]
    }]);
    links++;
  }
  figma.currentPage.flowStartingPoints = [{ nodeId: ctx.frames.home.id, name: "First crypto buy" }];
  figma.viewport.scrollAndZoomIntoView(sections);
  figma.notify("Built " + Object.keys(ctx.frames).length + " frames and " + links + " prototype links.");
}

run().then(() => figma.closePlugin()).catch((e) => {
  console.error(e);
  figma.closePlugin("Steady import failed: " + (e && e.message ? e.message : e));
});
