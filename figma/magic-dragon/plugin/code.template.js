/* Magic Dragon screens: builds the Gallery iPhone app as an editable Figma file.
   Generated by figma/magic-dragon/build.js from the HTML screens. Run it once in an
   empty Figma design file: Plugins > Development > Import plugin from manifest.

   Pages: Cover, Design system (colour variables, text styles, component sets),
   Screens (every frame, grouped, with design notes and prototype links) and Motion. */

const DATA = /*__DATA__*/null;

const W = 390, H = 844, GAP = 120;
const INK = "#16131B", INK2 = "#5F5A66", INK3 = "#8E8994";
const ctx = {
  font: null, vars: [], byHex: {}, styles: {}, images: {},
  comps: {}, compTrees: {}, sets: {}, frames: {}, gos: [], holder: null,
  building: 0, detached: 0, links: 0
};

/* ---------------------------------------------------------------- colour */
function hex(c) {
  const h = (v) => Math.round(v * 255).toString(16).padStart(2, "0");
  return ("#" + h(c.r) + h(c.g) + h(c.b)).toUpperCase();
}
function rgb(hexStr) {
  const n = parseInt(hexStr.slice(1), 16);
  return { r: ((n >> 16) & 255) / 255, g: ((n >> 8) & 255) / 255, b: (n & 255) / 255 };
}
const PREFER = {
  fill: ["Surface/", "Brand/", "Status/", "Map/", "Device/", "Text/", "Border/"],
  text: ["Text/", "Brand/", "Status/", "Surface/", "Device/"],
  stroke: ["Border/", "Brand/", "Surface/", "Map/", "Text/"]
};
function varFor(c, role) {
  const list = ctx.byHex[hex(c)];
  if (!list) return null;
  for (const pre of PREFER[role] || PREFER.fill) {
    const hit = list.find((t) => t.name.indexOf(pre) === 0);
    if (hit) return hit.v;
  }
  return list[0].v;
}
function paint(c, role) {
  let p = { type: "SOLID", color: { r: c.r, g: c.g, b: c.b } };
  if (c.a !== undefined && c.a < 1) p.opacity = c.a;
  const v = varFor(c, role);
  if (v) p = figma.variables.setBoundVariableForPaint(p, "color", v);
  return p;
}
function solid(hexStr, opacity) { return paint(Object.assign(rgb(hexStr), { a: opacity === undefined ? 1 : opacity }), "fill"); }

function image(id) {
  if (!ctx.images[id]) ctx.images[id] = figma.createImage(figma.base64Decode(DATA.images[id]));
  return ctx.images[id];
}
function imagePaint(f) {
  const p = { type: "IMAGE", imageHash: image(f.img).hash, scaleMode: f.scaleMode || "FILL" };
  if (f.scaleMode === "CROP" && f.transform) p.imageTransform = f.transform;
  return p;
}
function gradientPaint(g) {
  const a = (g.angle * Math.PI) / 180;
  const d = { x: Math.sin(a), y: -Math.cos(a) };
  const L = Math.abs(d.x) + Math.abs(d.y) || 1;
  const p = { x: -d.y, y: d.x };
  return {
    type: "GRADIENT_LINEAR",
    gradientTransform: [[d.x / L, d.y / L, 0.5 - (0.5 * d.x + 0.5 * d.y) / L], [p.x / L, p.y / L, 0.5 - (0.5 * p.x + 0.5 * p.y) / L]],
    gradientStops: g.stops.map((s) => ({ position: Math.max(0, Math.min(1, s.position)), color: { r: s.color.r, g: s.color.g, b: s.color.b, a: s.color.a } }))
  };
}
function paints(list, role) {
  return (list || []).map((f) => (f.type === "solid" ? paint(f.color, role) : f.type === "image" ? imagePaint(f) : gradientPaint(f)));
}

/* ---------------------------------------------------------------- setup */
async function setupFonts() {
  const all = await figma.listAvailableFontsAsync();
  const norm = (s) => s.toLowerCase().replace(/[\s-]+/g, "");
  const NAMES = { 400: ["Regular"], 500: ["Medium"], 600: ["SemiBold", "Semi Bold", "Demi Bold"], 700: ["Bold"] };
  function pick(family) {
    const styles = all.filter((f) => f.fontName.family === family).map((f) => f.fontName.style);
    const map = {};
    for (const w of [400, 500, 600, 700]) {
      const hit = styles.find((s) => NAMES[w].some((n) => norm(n) === norm(s)));
      if (!hit) return null;
      map[w] = hit;
    }
    return map;
  }
  let family = "Geist", styles = pick("Geist");
  if (!styles) { family = "Inter"; styles = pick("Inter") || { 400: "Regular", 500: "Medium", 600: "Semi Bold", 700: "Bold" }; }
  ctx.font = { family, styles, fallback: family !== "Geist" };
  for (const w of [400, 500, 600, 700]) await figma.loadFontAsync({ family, style: styles[w] });
}
function fontFor(weight) {
  const w = weight >= 650 ? 700 : weight >= 550 ? 600 : weight >= 450 ? 500 : 400;
  return { family: ctx.font.family, style: ctx.font.styles[w] };
}

function setupVariables() {
  const coll = figma.variables.createVariableCollection("Magic Dragon");
  const mode = coll.modes[0].modeId;
  coll.renameMode(mode, "Light");
  for (const t of DATA.tokens) {
    const v = figma.variables.createVariable(t.name, coll, "COLOR");
    v.setValueForMode(mode, Object.assign(rgb(t.hex), { a: 1 }));
    if (t.description) v.description = t.description;
    if (t.cssVar) { try { v.setVariableCodeSyntax("WEB", "var(" + t.cssVar + ")"); } catch (e) { /* older Figma */ } }
    const rec = { name: t.name, hex: t.hex, token: t, v };
    ctx.vars.push(rec);
    (ctx.byHex[t.hex.toUpperCase()] = ctx.byHex[t.hex.toUpperCase()] || []).push(rec);
  }
}

async function setupTextStyles() {
  for (const s of DATA.typeStyles) {
    const st = figma.createTextStyle();
    st.name = s.name;
    st.fontName = fontFor(s.weight);
    st.fontSize = s.size;
    st.lineHeight = s.lineHeight ? { unit: "PIXELS", value: s.lineHeight } : { unit: "AUTO" };
    st.letterSpacing = { unit: "PIXELS", value: s.letterSpacing };
    st.description = s.size + "/" + (s.lineHeight || "auto") + ", " + ctx.font.family + " " + fontFor(s.weight).style + (ctx.font.fallback ? " (Geist in the app)" : "");
    ctx.styles[s.key] = st;
  }
}

/* ---------------------------------------------------------------- text */
function layoutText(t, n) {
  t.textAlignHorizontal = n.align || "LEFT";
  if (n.wrap) {
    t.resize(Math.max(1, n.w + (n.truncate ? 0 : 1)), Math.max(1, n.h));
    t.textAutoResize = "HEIGHT";
    if (n.truncate) { t.textTruncation = "ENDING"; t.maxLines = n.maxLines || 1; }
  } else {
    t.textAutoResize = "WIDTH_AND_HEIGHT";
  }
}

async function styleText(t, n, withLayout) {
  const first = n.runs[0].style;
  t.fontName = fontFor(first.weight);
  t.characters = n.chars;
  for (const r of n.runs) {
    const st = r.style;
    if (r.e <= r.s) continue;
    const ts = r.ts && ctx.styles[r.ts];
    if (ts) {
      await t.setRangeTextStyleIdAsync(r.s, r.e, ts.id);
      const styleLH = ts.lineHeight.unit === "PIXELS" ? ts.lineHeight.value : null;
      if ((st.lineHeight || null) !== styleLH) t.setRangeLineHeight(r.s, r.e, st.lineHeight ? { unit: "PIXELS", value: st.lineHeight } : { unit: "AUTO" });
    } else {
      t.setRangeFontName(r.s, r.e, fontFor(st.weight));
      t.setRangeFontSize(r.s, r.e, st.size);
      t.setRangeLineHeight(r.s, r.e, st.lineHeight ? { unit: "PIXELS", value: st.lineHeight } : { unit: "AUTO" });
    }
    if (!ts || Math.abs(ts.letterSpacing.value - st.letterSpacing) > 0.04) t.setRangeLetterSpacing(r.s, r.e, { unit: "PIXELS", value: st.letterSpacing });
    if (st.color) t.setRangeFills(r.s, r.e, [paint(st.color, "text")]);
    if (st.decoration) t.setRangeTextDecoration(r.s, r.e, st.decoration);
  }
  if (withLayout !== false) layoutText(t, n);
}

async function makeText(n, parent) {
  const t = figma.createText();
  parent.appendChild(t);
  await styleText(t, n, true);
  t.name = n.name || n.chars.slice(0, 40);
  t.x = n.x;
  t.y = n.y;
  return t;
}

function label(text, size, weight, x, y, width, color) {
  const t = figma.createText();
  t.fontName = fontFor(weight);
  t.characters = text;
  t.fontSize = size;
  t.lineHeight = { unit: "PERCENT", value: 140 };
  t.fills = [paint(Object.assign(rgb(color || INK), { a: 1 }), "text")];
  if (width) { t.resize(width, 20); t.textAutoResize = "HEIGHT"; }
  t.x = x;
  t.y = y;
  t.name = text.slice(0, 40);
  return t;
}

/* ---------------------------------------------------------------- frames, svg, images */
function setRadius(f, r) {
  if (!r) return;
  if (r[0] === r[1] && r[0] === r[2] && r[0] === r[3]) f.cornerRadius = r[0];
  else { f.topLeftRadius = r[0]; f.topRightRadius = r[1]; f.bottomRightRadius = r[2]; f.bottomLeftRadius = r[3]; }
}
function setStroke(f, s) {
  if (!s || !s.color) { f.strokes = []; return; }
  f.strokes = [paint(s.color, "stroke")];
  f.strokeAlign = "INSIDE";
  if (s.top === s.right && s.top === s.bottom && s.top === s.left) f.strokeWeight = s.top;
  else { f.strokeTopWeight = s.top; f.strokeRightWeight = s.right; f.strokeBottomWeight = s.bottom; f.strokeLeftWeight = s.left; }
  if (s.dashed) f.dashPattern = [4, 4];
}
function effectsOf(list) {
  return (list || []).map((e) => ({
    type: e.inset ? "INNER_SHADOW" : "DROP_SHADOW", color: { r: e.color.r, g: e.color.g, b: e.color.b, a: e.color.a },
    offset: { x: e.x, y: e.y }, radius: e.blur, spread: e.spread || 0, visible: true, blendMode: "NORMAL"
  }));
}
function styleFrame(f, n) {
  f.name = n.name || "Frame";
  f.resize(Math.max(0.01, n.w), Math.max(0.01, n.h));
  f.fills = paints(n.fills, "fill");
  setStroke(f, n.stroke);
  setRadius(f, n.radius);
  f.clipsContent = !!n.clip;
  if (n.opacity !== undefined && n.opacity < 1) f.opacity = n.opacity;
  if (n.effects && n.effects.length) f.effects = effectsOf(n.effects);
}

function makeSvg(n, parent) {
  const s = figma.createNodeFromSvg(n.svg);
  parent.appendChild(s);
  s.name = n.name || "Icon";
  s.clipsContent = true;
  if (n.opacity !== undefined && n.opacity < 1) s.opacity = n.opacity;
  s.x = n.x;
  s.y = n.y;
  return s;
}

function makeImage(n, parent) {
  const r = figma.createRectangle();
  parent.appendChild(r);
  r.name = n.name || "Image";
  r.resize(Math.max(0.01, n.w), Math.max(0.01, n.h));
  r.fills = n.fill && n.fill.img ? [imagePaint(n.fill)] : [solid("#EFEDE9")];
  setRadius(r, n.radius);
  if (n.opacity !== undefined && n.opacity < 1) r.opacity = n.opacity;
  r.x = n.x;
  r.y = n.y;
  return r;
}

function track(node, n) {
  if (n.go && !ctx.building) ctx.gos.push({ node, go: n.go });
  return node;
}

async function buildChildren(n, f) {
  for (const c of n.children || []) if (!c.hidden) await buildNode(c, f);
}

async function buildNode(n, parent) {
  if (n.type === "text") return track(await makeText(n, parent), n);
  if (n.type === "svg") return track(makeSvg(n, parent), n);
  if (n.type === "image") return track(makeImage(n, parent), n);
  if (n.comp) {
    const inst = await instanceFor(n, parent);
    if (inst) return inst;
  }
  const f = figma.createFrame();
  parent.appendChild(f);
  styleFrame(f, n);
  if (n.comp) f.name = n.comp.set;
  f.x = n.x;
  f.y = n.y;
  await buildChildren(n, f);
  return track(f, n);
}

/* ---------------------------------------------------------------- components */
const keyOf = (n) => n.comp.set + "|" + (n.comp.variant || "");

function autoLayoutFor(comp, n) {
  const set = n.comp.set;
  if (set !== "Button" && set !== "Chip") return;
  const t = (n.children || []).find((c) => c.type === "text");
  comp.layoutMode = "HORIZONTAL";
  comp.primaryAxisAlignItems = "CENTER";
  comp.counterAxisAlignItems = "CENTER";
  comp.itemSpacing = 8;
  if (set === "Chip" && t) {
    comp.paddingLeft = comp.paddingRight = Math.max(0, Math.round(t.x));
    comp.paddingTop = comp.paddingBottom = Math.max(0, Math.round((n.h - t.h) / 2));
    comp.primaryAxisSizingMode = "AUTO";
    comp.counterAxisSizingMode = "AUTO";
  } else {
    comp.primaryAxisSizingMode = "FIXED";
    comp.counterAxisSizingMode = "FIXED";
  }
}

async function makeComponent(n) {
  const comp = figma.createComponent();
  ctx.holder.appendChild(comp);
  styleFrame(comp, n);
  comp.name = n.comp.variant || n.comp.set;
  ctx.building++;
  try { await buildChildren(n, comp); } finally { ctx.building--; }
  autoLayoutFor(comp, n);
  const key = keyOf(n);
  ctx.comps[key] = comp;
  ctx.compTrees[key] = n;
  (ctx.sets[n.comp.set] = ctx.sets[n.comp.set] || []).push(comp);
  return comp;
}

const diff = (a, b) => Math.abs((a || 0) - (b || 0)) > 0.5;
const far = (a, b) => Math.abs((a || 0) - (b || 0)) > 1.5;
const same = (a, b) => JSON.stringify(a === undefined ? null : a) === JSON.stringify(b === undefined ? null : b);
/* Figma doesn't let instances move or resize their layers; build.js only makes an
   instance when the layers already line up, so these are best-effort extras. */
function attempt(fn) { try { fn(); return true; } catch (e) { ctx.skipped = (ctx.skipped || 0) + 1; return false; } }

async function applyOv(fn, n, m, isRoot) {
  if (n.hidden) { fn.visible = false; return; }
  if (n.go && !ctx.building) ctx.gos.push({ node: fn, go: n.go });
  const inAuto = !isRoot && fn.parent && fn.parent.layoutMode && fn.parent.layoutMode !== "NONE";
  if (!isRoot && !inAuto) {
    if (far(n.x, m.x)) attempt(() => { fn.x = n.x; });
    if (far(n.y, m.y)) attempt(() => { fn.y = n.y; });
  }
  if (n.type === "text") {
    const sameText = n.chars === m.chars && same(n.runs, m.runs);
    const sameBox = !far(n.w, m.w) && !far(n.h, m.h) && n.wrap === m.wrap && n.align === m.align;
    if (!sameText) await styleText(fn, n, false);
    if (!sameBox && !inAuto && n.wrap) attempt(() => layoutText(fn, n));
    return;
  }
  if (n.type === "image") {
    if (!same(n.fill, m.fill)) fn.fills = n.fill && n.fill.img ? [imagePaint(n.fill)] : [];
    if (!isRoot && (far(n.w, m.w) || far(n.h, m.h))) attempt(() => fn.resize(Math.max(0.01, n.w), Math.max(0.01, n.h)));
    if ((n.opacity || 1) !== (m.opacity || 1)) fn.opacity = n.opacity;
    if (!same(n.radius, m.radius)) attempt(() => setRadius(fn, n.radius));
    return;
  }
  if (n.type === "svg") return;
  const hugs = n.comp && n.comp.set === "Chip";
  if (!isRoot && !inAuto && !hugs && (far(n.w, m.w) || far(n.h, m.h))) attempt(() => fn.resize(Math.max(0.01, n.w), Math.max(0.01, n.h)));
  if (!same(n.fills, m.fills)) fn.fills = paints(n.fills, "fill");
  if (!same(n.stroke, m.stroke)) attempt(() => setStroke(fn, n.stroke));
  if ((n.opacity || 1) !== (m.opacity || 1)) fn.opacity = n.opacity;
  if (!same(n.radius, m.radius)) attempt(() => setRadius(fn, n.radius));
  if (!same(n.effects, m.effects)) fn.effects = effectsOf(n.effects);
  const kids = fn.children || [];
  const nk = n.children || [], mk = m.children || [];
  for (let i = 0; i < nk.length && i < kids.length && i < mk.length; i++) await applyOv(kids[i], nk[i], mk[i], false);
}

async function instanceFor(n, parent) {
  const key = keyOf(n);
  if (!ctx.comps[key]) await makeComponent(n);
  const main = ctx.compTrees[key];
  if (n.detach || (main.sig && n.sig && main.sig !== n.sig)) { ctx.detached++; return null; }
  const inst = ctx.comps[key].createInstance();
  parent.appendChild(inst);
  inst.x = n.x;
  inst.y = n.y;
  if (n.comp.set !== "Chip" && (diff(n.w, main.w) || diff(n.h, main.h))) inst.resize(Math.max(0.01, n.w), Math.max(0.01, n.h));
  await applyOv(inst, n, main, true);
  return inst;
}

/* ---------------------------------------------------------------- pages */
function newSection(page, name, fill) {
  const s = figma.createSection();
  page.appendChild(s);
  s.name = name;
  if (fill) s.fills = [solid(fill)];
  return s;
}

async function buildScreens(page) {
  page.appendChild(label(DATA.title + ": " + DATA.subtitle, 40, 600, 0, -340));
  page.appendChild(label("Every frame is clickable: select Launch and press Present. Products and prices are examples; the address, driver and order number are placeholders.", 20, 400, 0, -276, 1700, INK2));
  let y = 0;
  const sections = [];
  for (const name of DATA.sections) {
    const list = DATA.screens.filter((s) => s.section === name);
    if (!list.length) continue;
    const section = newSection(page, name, "#E9E7E2");
    const pad = 80;
    let x = pad;
    let tallest = 0;
    for (const s of list) {
      const frame = figma.createFrame();
      section.appendChild(frame);
      styleFrame(frame, Object.assign({}, s.tree, { name: s.title }));
      frame.x = x;
      frame.y = pad;
      frame.clipsContent = true;
      await buildChildren(s.tree, frame);
      ctx.frames[s.id] = frame;
      const title = label((s.num ? s.num + "  " : "") + s.title, 20, 600, x, pad + H + 32);
      if (s.num) title.setRangeFills(0, s.num.length, [paint(Object.assign(rgb(INK3), { a: 1 }), "text")]);
      section.appendChild(title);
      if (s.note) {
        const note = label(s.note, 15, 400, x, pad + H + 68, W, INK2);
        section.appendChild(note);
        tallest = Math.max(tallest, Math.ceil(s.note.length / 52) * 21);
      }
      x += W + GAP;
    }
    const h = pad + H + 68 + tallest + pad;
    section.resizeWithoutConstraints(x - GAP + pad, h);
    section.x = 0;
    section.y = y;
    y += h + 160;
    sections.push(section);
  }
  return sections;
}

async function buildBoard(page, board, startY, fill) {
  const out = [];
  let y = startY || 0;
  for (const sec of board.sections) {
    if (sec.bare) {
      for (const c of sec.children) out.push(await buildNode(c, page));
      continue;
    }
    const pad = 80;
    const section = newSection(page, sec.name, fill || "#E9E7E2");
    for (const c of sec.children) {
      const node = await buildNode(c, section);
      node.x += pad;
      node.y += pad;
    }
    section.resizeWithoutConstraints(sec.w + pad * 2, sec.h + pad * 2);
    section.x = 0;
    section.y = y;
    y += sec.h + pad * 2 + 120;
    out.push(section);
  }
  out.endY = y;
  return out;
}

function swatch(rec) {
  const card = figma.createFrame();
  card.name = rec.name;
  card.fills = [];
  card.clipsContent = false;
  card.resize(200, 196);
  const chip = figma.createRectangle();
  card.appendChild(chip);
  chip.name = "Swatch";
  chip.resize(200, 104);
  chip.cornerRadius = 12;
  chip.fills = [figma.variables.setBoundVariableForPaint({ type: "SOLID", color: rgb(rec.hex) }, "color", rec.v)];
  chip.strokes = [{ type: "SOLID", color: rgb(INK), opacity: 0.08 }];
  chip.strokeAlign = "INSIDE";
  chip.strokeWeight = 1;
  card.appendChild(label(rec.name.split("/").slice(1).join("/"), 15, 600, 0, 116));
  card.appendChild(label(rec.hex + (rec.token.cssVar ? "  " + rec.token.cssVar : ""), 13, 400, 0, 140, null, INK2));
  if (rec.token.description) card.appendChild(label(rec.token.description, 12, 400, 0, 162, 200, INK3));
  return card;
}

function parseVariant(name) {
  const o = {};
  String(name).split(",").forEach((p) => { const [k, v] = p.split("=").map((s) => s.trim()); if (v !== undefined) o[k] = v; });
  return o;
}

async function buildDesignSystem(page) {
  page.appendChild(label("Design system", 40, 600, 0, -300));
  page.appendChild(label("The mark, colour variables (Magic Dragon collection), text styles in " + ctx.font.family + (ctx.font.fallback ? " (the app uses Geist; it was not available in this Figma, so styles fall back to Inter)" : "") + ", and the components the screens are built from.", 20, 400, 0, -236, 1700, INK2));
  const pad = 80;
  let y = 0;

  /* mark */
  if (DATA.boards.mark) y = (await buildBoard(page, DATA.boards.mark, 0, "#FFFFFF")).endY;

  /* colour */
  const colour = newSection(page, "Colour", "#FFFFFF");
  let cy = pad, maxX = 0;
  for (const g of DATA.tokenGroups) {
    const recs = ctx.vars.filter((r) => r.name.split("/")[0] === g);
    if (!recs.length) continue;
    colour.appendChild(label(g, 20, 600, pad, cy));
    cy += 48;
    let x = pad;
    recs.forEach((r) => {
      const c = swatch(r);
      colour.appendChild(c);
      c.x = x;
      c.y = cy;
      x += 224;
      maxX = Math.max(maxX, x);
    });
    cy += 236;
  }
  colour.resizeWithoutConstraints(Math.max(1800, maxX - 24 + pad), cy + pad - 40);
  colour.x = 0;
  colour.y = y;
  y += cy + pad + 120;

  /* type */
  const type = newSection(page, "Type", "#FFFFFF");
  let ty = pad;
  type.appendChild(label("Style", 13, 600, pad, ty, null, INK3));
  type.appendChild(label("Spec", 13, 600, pad + 300, ty, null, INK3));
  type.appendChild(label("Sample", 13, 600, pad + 620, ty, null, INK3));
  ty += 36;
  for (const s of DATA.typeStyles) {
    const st = ctx.styles[s.key];
    const rowH = Math.max(s.lineHeight || s.size * 1.3, 22) + 28;
    const line = figma.createRectangle();
    type.appendChild(line);
    line.name = "Divider";
    line.resize(1640, 1);
    line.fills = [solid("#E7E4DF")];
    line.x = pad;
    line.y = ty;
    type.appendChild(label(s.name, 15, 500, pad, ty + 14));
    const ls = Math.round(s.letterSpacing * 100) / 100;
    type.appendChild(label(fontFor(s.weight).style + " · " + s.size + "/" + (s.lineHeight || "auto") + (ls ? " · " + ls : ""), 13, 400, pad + 300, ty + 16, null, INK2));
    const t = figma.createText();
    type.appendChild(t);
    t.fontName = fontFor(s.weight);
    t.characters = s.sample;
    await t.setTextStyleIdAsync(st.id);
    t.fills = [paint(Object.assign(rgb(INK), { a: 1 }), "text")];
    t.name = s.name;
    t.x = pad + 620;
    t.y = ty + 14;
    ty += rowH;
  }
  type.resizeWithoutConstraints(1800, ty + pad);
  type.x = 0;
  type.y = y;
  y += ty + pad + 120;

  /* components */
  const comps = newSection(page, "Components", "#FFFFFF");
  const order = DATA.setOrder.filter((n) => ctx.sets[n]).concat(Object.keys(ctx.sets).filter((n) => DATA.setOrder.indexOf(n) < 0));
  const cols = [{ x: pad, y: pad }, { x: pad + 1360, y: pad }];
  let widest = 0;
  for (const name of order) {
    const list = ctx.sets[name];
    const col = name === "Button" || name === "Product card" ? cols[0] : cols[0].y <= cols[1].y ? cols[0] : cols[1];
    const doc = DATA.componentDocs[name] || "";
    comps.appendChild(label(name, 24, 600, col.x, col.y));
    if (doc) comps.appendChild(label(doc, 15, 400, col.x, col.y + 40, 620, INK2));
    let top = col.y + (doc ? 40 + Math.ceil(doc.length / 80) * 21 + 24 : 52);
    let node;
    if (list.length > 1 || list[0].name.indexOf("=") > -1) {
      const props = Object.keys(parseVariant(list[0].name));
      const vals = props.map((p) => []);
      list.forEach((c) => { const v = parseVariant(c.name); props.forEach((p, i) => { if (vals[i].indexOf(v[p]) < 0) vals[i].push(v[p]); }); });
      const wide = Math.max(...list.map((c) => c.width)) > 330;
      let colKey = props[0], rowKey = props[1];
      if (props.length === 1 && wide) { rowKey = props[0]; colKey = null; }
      const colVals = colKey ? vals[props.indexOf(colKey)] : [null];
      const rowVals = rowKey ? vals[props.indexOf(rowKey)] : [null];
      const cell = (c) => { const v = parseVariant(c.name); return [colKey ? colVals.indexOf(v[colKey]) : 0, rowKey ? rowVals.indexOf(v[rowKey]) : 0]; };
      const colW = colVals.map(() => 0), rowH = rowVals.map(() => 0);
      list.forEach((c) => { const [ci, ri] = cell(c); colW[ci] = Math.max(colW[ci], c.width); rowH[ri] = Math.max(rowH[ri], c.height); });
      const g = 32, inner = 32;
      const colX = [], rowY = [];
      colW.reduce((acc, w, i) => { colX[i] = acc; return acc + w + g; }, inner);
      rowH.reduce((acc, h, i) => { rowY[i] = acc; return acc + h + g; }, inner);
      const rowLabelW = rowKey ? 120 : 0;
      const setX = col.x + rowLabelW;
      if (colKey && colVals.length > 1) {
        colVals.forEach((v, i) => comps.appendChild(label(v, 13, 500, setX + colX[i], top, null, INK2)));
        top += 28;
      }
      node = figma.combineAsVariants(list, comps);
      node.name = name;
      list.forEach((c) => { const [ci, ri] = cell(c); c.x = colX[ci]; c.y = rowY[ri]; });
      const totalW = colX[colX.length - 1] + colW[colW.length - 1] + inner;
      const totalH = rowY[rowY.length - 1] + rowH[rowH.length - 1] + inner;
      node.resizeWithoutConstraints(totalW, totalH);
      node.strokes = [{ type: "SOLID", color: rgb("#9747FF") }];
      node.strokeWeight = 1;
      node.dashPattern = [10, 5];
      node.cornerRadius = 8;
      node.fills = list.some((c) => /Appearance=Light/.test(c.name)) ? [solid("#BEB9B2")] : [];
      node.x = setX;
      node.y = top;
      if (rowKey) rowVals.forEach((v, i) => comps.appendChild(label(v, 13, 500, col.x, top + rowY[i] + Math.max(0, rowH[i] / 2 - 9), null, INK2)));
      if (doc) node.description = doc;
      widest = Math.max(widest, setX + totalW);
      col.y = top + totalH + 120;
    } else {
      node = list[0];
      comps.appendChild(node);
      node.x = col.x;
      node.y = top;
      if (doc) node.description = doc;
      widest = Math.max(widest, col.x + node.width);
      col.y = top + node.height + 120;
    }
  }
  comps.resizeWithoutConstraints(Math.max(1800, widest + pad), Math.max(cols[0].y, cols[1].y) + pad - 120);
  comps.x = 0;
  comps.y = y;
}

async function wirePrototype(screensPage) {
  const seen = new Set();
  const transition = { type: "DISSOLVE", easing: { type: "EASE_OUT" }, duration: 0.2 };
  for (const g of ctx.gos) {
    if (seen.has(g.node.id)) continue;
    const dest = g.go === "back" ? null : ctx.frames[g.go];
    if (g.go !== "back" && !dest) continue;
    const action = g.go === "back" ? { type: "BACK" } : { type: "NODE", destinationId: dest.id, navigation: "NAVIGATE", transition };
    const reaction = { trigger: { type: "ON_CLICK" }, actions: [action] };
    try {
      await g.node.setReactionsAsync([reaction]);
      seen.add(g.node.id);
      ctx.links++;
    } catch (e) {
      let p = g.node.parent, top = null;
      while (p && p.type !== "PAGE" && p.type !== "SECTION") { if (p.type === "INSTANCE") top = p; p = p.parent; }
      if (top && !seen.has(top.id)) {
        try { await top.setReactionsAsync([reaction]); seen.add(top.id); ctx.links++; } catch (e2) { /* skip */ }
      }
    }
  }
  for (const auto of DATA.flow.autos || []) {
    if (!ctx.frames[auto.from] || !ctx.frames[auto.to]) continue;
    await ctx.frames[auto.from].setReactionsAsync([{ trigger: { type: "AFTER_TIMEOUT", timeout: auto.seconds },
      actions: [{ type: "NODE", destinationId: ctx.frames[auto.to].id, navigation: "NAVIGATE", transition: { type: "DISSOLVE", easing: { type: "EASE_OUT" }, duration: 0.3 } }] }]);
    ctx.links++;
  }
  const start = ctx.frames[DATA.flow.start];
  if (start) screensPage.flowStartingPoints = [{ nodeId: start.id, name: DATA.flow.name }];
}

async function run() {
  if (!DATA) throw new Error("No screen data. Run figma/magic-dragon/build.js first.");
  await setupFonts();
  setupVariables();
  await setupTextStyles();

  let cover = figma.currentPage;
  if (cover.children.length) { cover = figma.createPage(); figma.root.insertChild(0, cover); }
  cover.name = "Cover";
  const ds = figma.createPage(); ds.name = "Design system";
  const screens = figma.createPage(); screens.name = "Screens";
  const motion = figma.createPage(); motion.name = "Motion";

  ctx.holder = figma.createFrame();
  ctx.holder.name = "Components (building)";
  ctx.holder.fills = [];
  ctx.holder.clipsContent = false;
  ds.appendChild(ctx.holder);

  for (const c of DATA.components) {
    const k = keyOf(c);
    if (!ctx.comps[k]) await makeComponent(c);
  }
  const screenSections = await buildScreens(screens);
  const coverNodes = await buildBoard(cover, DATA.boards.cover);
  await buildBoard(motion, DATA.boards.motion);
  await buildDesignSystem(ds);
  ctx.holder.remove();
  await wirePrototype(screens);

  const thumb = coverNodes.find((n) => n.type === "FRAME");
  if (thumb) { try { await figma.setFileThumbnailNodeAsync(thumb); } catch (e) { /* optional */ } }
  await figma.setCurrentPageAsync(screens);
  figma.viewport.scrollAndZoomIntoView(screenSections);
  const variants = Object.values(ctx.sets).reduce((n, l) => n + l.length, 0);
  console.log("Magic Dragon import: " + ctx.detached + " component occurrences drawn as plain frames, " + (ctx.skipped || 0) + " overrides Figma refused");
  figma.notify("Magic Dragon: " + Object.keys(ctx.frames).length + " screens, " + variants + " component variants, " + ctx.links + " prototype links" +
    (ctx.font.fallback ? ". Geist isn't installed, so text uses Inter." : "."), { timeout: 8000 });
}

run().then(() => figma.closePlugin()).catch((e) => {
  console.error(e);
  figma.closePlugin("Magic Dragon import failed: " + (e && e.message ? e.message : e));
});
